package com.bdaniel.loyscan

import android.content.Context
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.graphics.Canvas
import android.graphics.Color
import androidx.test.core.app.ApplicationProvider
import androidx.test.ext.junit.runners.AndroidJUnit4
import com.bdaniel.loyscan.testing.adaptiveLayers
import com.google.common.truth.Truth.assertThat
import com.google.common.truth.Truth.assertWithMessage
import java.io.File
import kotlin.math.abs
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.annotation.GraphicsMode

/**
 * Play's 512×512 store icon (#75) is `play/store-icon.png`, rendered from the launcher icon's adaptive layers: the
 * visible 72dp centre (18..90dp) of the 108dp background and foreground, scaled to 512px, as Android Studio's Play
 * Store icon export does. Play draws the rounded corners and the shadow itself, so the PNG is a full, opaque square.
 *
 * The PNG is generated by this test: [storeIcon_isTheLauncherIconsLayersRenderedAt512] always writes a fresh rendering
 * to `app/build/store-icon/store-icon.png`; after an intended icon change, copy that over `play/store-icon.png`. The
 * hand-worked pixels in [storeIcon_meetsPlaysSpec] check the crop and the scale, which a rendering compared with itself
 * can't.
 */
@RunWith(AndroidJUnit4::class)
@GraphicsMode(GraphicsMode.Mode.NATIVE)
class StoreIconTest {

    private val context = ApplicationProvider.getApplicationContext<Context>()

    @Test
    fun storeIcon_isTheLauncherIconsLayersRenderedAt512() {
        val fresh = render()
        FRESH.parentFile!!.mkdirs()
        FRESH.outputStream().use { fresh.compress(Bitmap.CompressFormat.PNG, 100, it) }
        val committed = committed()

        var maxDiff = 0
        var differing = 0
        for (y in 0 until SIZE) for (x in 0 until SIZE) {
            val diff = channelDiff(committed.getPixel(x, y), fresh.getPixel(x, y))
            maxDiff = maxOf(maxDiff, diff)
            if (diff > TOLERANCE) differing++
        }
        assertWithMessage(
            "pixels of play/store-icon.png that differ from the launcher icon's layers by more than $TOLERANCE " +
                "(largest difference $maxDiff); after an intended icon change, copy app/build/store-icon/store-icon.png to play/store-icon.png",
        ).that(differing).isEqualTo(0)
    }

    @Test
    fun storeIcon_meetsPlaysSpec() {
        val bytes = STORE_ICON.also(::assertExists).readBytes()
        assertWithMessage("file size").that(bytes.size).isAtMost(1024 * 1024)
        // PNG header: bit depth at byte 24, colour type at byte 25 (6 = RGBA), i.e. 32 bits per pixel.
        assertWithMessage("bit depth").that(bytes[24].toInt()).isEqualTo(8)
        assertWithMessage("colour type").that(bytes[25].toInt()).isEqualTo(6)

        val icon = committed()
        assertThat(icon.width).isEqualTo(SIZE)
        assertThat(icon.height).isEqualTo(SIZE)
        val transparent = (0 until SIZE).sumOf { y -> (0 until SIZE).count { x -> Color.alpha(icon.getPixel(x, y)) < 255 } }
        assertWithMessage("pixels that aren't fully opaque").that(transparent).isEqualTo(0)

        // Worked by hand: a dp of the 108dp layer is at px = (dp - 18) * 512 / 72. The front card spans 29..79dp
        // across (ic_launcher_foreground.xml), so its sides are at x = 78.2 and 433.8; row 60dp is y = 298.7, where the
        // back card reaches 27.0dp (x = 64) on the left and less than 79dp on the right. A wrong crop or scale moves them.
        assertColour(icon, 0, 0, PLUM, "the corner")
        assertColour(icon, 511, 511, PLUM, "the opposite corner")
        assertColour(icon, 50, 298, PLUM, "left of both cards")
        assertColour(icon, 85, 298, WHITE, "just inside the front card's left side")
        assertColour(icon, 427, 298, WHITE, "just inside the front card's right side")
        assertColour(icon, 441, 298, PLUM, "just right of the front card")
    }

    private fun render(): Bitmap {
        // 108dp → 768px, so the visible 72dp are 512px, and the layer starts 18dp = 128px above and left of the icon.
        val layers = context.adaptiveLayers(R.mipmap.ic_launcher)
        val bitmap = Bitmap.createBitmap(SIZE, SIZE, Bitmap.Config.ARGB_8888)
        val canvas = Canvas(bitmap)
        listOf("background", "foreground").forEach { layer ->
            context.getDrawable(layers.getValue(layer))!!.apply { setBounds(-128, -128, 640, 640) }.draw(canvas)
        }
        return bitmap
    }

    /** Decoded from a stream closed here: `BitmapFactory.decodeFile` holds the file open on Windows (#88). */
    private fun committed(): Bitmap {
        assertExists(STORE_ICON)
        return STORE_ICON.inputStream().use { BitmapFactory.decodeStream(it) }!!
    }

    private fun assertExists(file: File) {
        assertWithMessage("play/store-icon.png is missing; copy app/build/store-icon/store-icon.png there after running this test")
            .that(file.isFile).isTrue()
    }

    private fun assertColour(icon: Bitmap, x: Int, y: Int, expected: Int, where: String) {
        assertWithMessage("colour at ($x,$y), $where: #%s", "%08X".format(icon.getPixel(x, y)))
            .that(channelDiff(icon.getPixel(x, y), expected)).isAtMost(TOLERANCE)
    }

    private fun channelDiff(a: Int, b: Int): Int = maxOf(
        abs(Color.alpha(a) - Color.alpha(b)),
        abs(Color.red(a) - Color.red(b)),
        abs(Color.green(a) - Color.green(b)),
        abs(Color.blue(a) - Color.blue(b)),
    )

    private companion object {
        const val SIZE = 512
        const val TOLERANCE = 2
        const val PLUM = 0xFF5B2A4E.toInt()
        const val WHITE = 0xFFFFFFFF.toInt()
        /** Tests run in `app/`. */
        val STORE_ICON = File("../play/store-icon.png")
        val FRESH = File("build/store-icon/store-icon.png")
    }
}
